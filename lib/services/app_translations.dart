  static String tr(String key, String langCode) {
    final lang = _localizedValues.containsKey(langCode) ? langCode : 'tr';
    return _localizedValues[lang]?[key] ?? _localizedValues['tr']?[key] ?? key;
  }

  static String translateSpeechType(String? speechType, String langCode) {
    if (speechType == null || speechType.isEmpty) return tr('speech_type_business', langCode);

    if (speechType == 'speech_type_politician' || speechType == 'Siyasetçi Konuşması') {
      return tr('speech_type_politician', langCode);
    }
    if (speechType == 'speech_type_imam' || speechType.contains('İmam') || speechType.contains('Hutbe')) {
      return tr('speech_type_imam', langCode);
    }
    if (speechType == 'speech_type_teacher_welcome' || speechType.contains('Tanışma')) {
      return tr('speech_type_teacher_welcome', langCode);
    }
    if (speechType == 'speech_type_teacher_farewell' || speechType.contains('Veda')) {
      return tr('speech_type_teacher_farewell', langCode);
    }
    if (speechType == 'speech_type_business' || speechType.contains('İş') || speechType.contains('Hitabet')) {
      return tr('speech_type_business', langCode);
    }
    if (speechType == 'speech_type_wedding' || speechType.contains('Düğün') || speechType.contains('Kutlama')) {
      return tr('speech_type_wedding', langCode);
    }
    return speechType;
  }

  static String translateLanguageName(String? languageName, String langCode) {
    if (languageName == null || languageName.isEmpty) return '';
    final lower = languageName.toLowerCase();

    if (lower == 'tr' || lower.contains('türk') || lower.contains('turk')) {
      return tr('lang_tr', langCode);
    }
    if (lower == 'en' || lower.contains('ing') || lower.contains('eng')) {
      return tr('lang_en', langCode);
    }
    if (lower == 'de' || lower.contains('alm') || lower.contains('ger')) {
      return tr('lang_de', langCode);
    }
    if (lower == 'es' || lower.contains('isp') || lower.contains('spa')) {
      return tr('lang_es', langCode);
    }
    if (lower == 'fr' || lower.contains('fra') || lower.contains('fre')) {
      return tr('lang_fr', langCode);
    }
    if (lower == 'ar' || lower.contains('arap') || lower.contains('arab')) {
      return tr('lang_ar', langCode);
    }
    if (lower == 'ru' || lower.contains('rus')) {
      return tr('lang_ru', langCode);
    }
    return languageName;
  }
